`timescale 1ns / 1ps

module tb_simple;

    // ============================================================
    // 参数
    // ============================================================
    parameter CLK_PERIOD = 10;          // 100MHz
    parameter SIM_CYCLES = 40;         // 仿真周期数

    // ============================================================
    // 信号
    // ============================================================
    reg clk;
    reg rst_n;

    // ============================================================
    // DUT
    // ============================================================
    top #(
        .IMEM_FILE ("bench_fib.mem"),
        .DMEM_FILE ("data.mem")
    ) u_top (
        .clk   (clk),
        .rst_n (rst_n)
    );

    // ============================================================
    // 时钟生成
    // ============================================================
    initial clk = 0;
    always #(CLK_PERIOD / 2) clk = ~clk;

    // ============================================================
    // 复位序列: 上电拉低 1 周期, 之后释放
    // ============================================================
    initial begin
        rst_n = 1'b0;
        #(CLK_PERIOD);                  // 保持低电平 1 个周期
        rst_n = 1'b1;
    end

    // ============================================================
    // 仿真控制: 运行指定周期后结束
    // ============================================================
    initial begin
        #(CLK_PERIOD * SIM_CYCLES);
        $writememh("result.mem", u_top.umem.u_dmem.mem);
        $display("=== Simulation finished after %0d cycles ===", SIM_CYCLES);
        $finish;
    end


endmodule
