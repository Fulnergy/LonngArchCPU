# ============================================================
# bench_core — ALU + Load/Store 简单测试 (无手动NOP)
#   期望结果:
#     $r3 = 8   (5+3)
#     $r4 = 2   (5-3)
#     $r10= 1   (5&3)
#     $r6 = 8,  $r7 = 2,  $r8 = 1   (load back)
#     $r9 = 10  (8+2)
# ============================================================

    addi.w    $r1, $r0, 5
    addi.w    $r2, $r0, 3
    add.w     $r3, $r1, $r2
    sub.w     $r4, $r1, $r2
    and       $r10, $r1, $r2

    addi.w    $r5, $r0, 0x100

    st.w      $r3, $r5, 0
    st.w      $r4, $r5, 4
    st.w      $r10, $r5, 8

    ld.w      $r6, $r5, 0
    ld.w      $r7, $r5, 4
    ld.w      $r8, $r5, 8

    add.w     $r9, $r6, $r7

dead_loop:
    b         dead_loop

