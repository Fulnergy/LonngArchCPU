# ============================================================
# BL / JIRL 测试 — 嵌套调用
#
# main  → BL outer_func → 计算并返回
# outer → 保存 $r1     → BL inner_func → 阶乘 → JIRL 返回
#        → 结果+100     → JIRL 返回 main
#
# 期望: $r20 = fact(5) + 100 = 120 + 100 = 220 = 0xDC
#
# 寄存器:
#   $r12 = n (5)
#   $r13 = i (循环计数)
#   $r20 = result
#   $r23 = outer_func 保存的返回地址
#
# 注意: 不主动插入 NOP, 依赖发射逻辑自动处理依赖/对齐
# ============================================================

# ── 入口 ── 00
    addi.w  $r12, $r0, 5         # $r12 = 5
    bl      outer_func           # 调用, $r1 = 返回地址

# ── 返回后死循环 ── 08
end:
    b       end

# ============================================================
# outer_func
# ============================================================
outer_func:
    or      $r23, $r1, $r0       # 保存返回地址
    bl      inner_func           # 嵌套调用  10

    addi.w  $r20, $r20, 100      # $r20 += 100
    jirl    $r0, $r23, 0         # 返回 main  18

# ============================================================
# inner_func: 迭代计算 factorial($r12)
# ============================================================
inner_func:
    addi.w  $r20, $r0, 1         # result = 1
    addi.w  $r13, $r0, 1         # i = 1  20

fact_loop:
    blt     $r12, $r13, fact_done # i > n → 结束
    mul.w   $r20, $r20, $r13     # result *= i  28
    addi.w  $r13, $r13, 1        # i++
    b       fact_loop            #  30

fact_done:
    jirl    $r0, $r1, 0          # 返回 outer_func
