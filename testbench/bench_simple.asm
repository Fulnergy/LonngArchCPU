# ============================================================
# LoongArch 32-bit 测试程序 — 全 ALU 指令覆盖
# 双发射布局: 左列为 slot0 (低32位), 右列为 slot1 (高32位)
# ============================================================

# ── 初始化: $r1=7, $r2=2 ──
    addi.w  $r1, $r0, 7       
    addi.w  $r2, $r0, 2       # PC=0x00

# ── 等待写回 (3对NOP, 保证 $r1/$r2 在 WB 写入后才被 ID 读到) ──
    addi.w  $r0, $r0, 0       
    addi.w  $r0, $r0, 0       # PC=0x08
    addi.w  $r0, $r0, 0       
    addi.w  $r0, $r0, 0       # PC=0x10
    addi.w  $r0, $r0, 0       
    addi.w  $r0, $r0, 0       # PC=0x18

# ============================================================
# 3R型 ALU (18条, $r1=7, $r2=2)
# ============================================================
    add.w   $r3,  $r1, $r2      
    sub.w   $r4,  $r1, $r2     # PC=0x20  $r3=9,  $r4=5
    slt     $r5,  $r1, $r2      
    sltu    $r6,  $r1, $r2     # PC=0x28  $r5=0,  $r6=0
    nor     $r7,  $r1, $r2      
    and     $r8,  $r1, $r2     # PC=0x30  $r7=-8, $r8=2
    or      $r9,  $r1, $r2      
    xor     $r10, $r1, $r2     # PC=0x38  $r9=7,  $r10=5
    sll.w   $r11, $r1, $r2      
    srl.w   $r12, $r1, $r2     # PC=0x40  $r11=28, $r12=1
    sra.w   $r13, $r1, $r2      
    mul.w   $r14, $r1, $r2     # PC=0x48  $r13=1, $r14=14
    mulh.w  $r15, $r1, $r2      
    mulh.wu $r16, $r1, $r2     # PC=0x50  $r15=0, $r16=0
    div.w   $r17, $r1, $r2      
    mod.w   $r18, $r1, $r2     # PC=0x58  $r17=3, $r18=1
    div.wu  $r19, $r1, $r2      
    mod.wu  $r20, $r1, $r2     # PC=0x60  $r19=3, $r20=1

# ============================================================
# I型 ALU (6条, $r1=7, imm=2)
# ============================================================
    addi.w  $r21, $r1, 2       
    andi    $r22, $r1, 2      # PC=0x68  $r21=9, $r22=2
    ori     $r23, $r1, 2       
    xori    $r24, $r1, 2      # PC=0x70  $r23=7, $r24=5
    slti    $r25, $r1, 2       
    sltui   $r26, $r1, 2      # PC=0x78  $r25=0, $r26=0

# ============================================================
# 移位立即数 (3条) + 特殊 (1条)
# ============================================================
    slli.w  $r27, $r1, 2       
    srli.w  $r28, $r1, 2      # PC=0x80  $r27=28, $r28=1
    srai.w  $r29, $r1, 2       
    lu12i.w $r30, 0           # PC=0x88  $r29=1, $r30=0

# ============================================================
# 死循环结束
# ============================================================
loop:
    b       loop           