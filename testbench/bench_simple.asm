# ============================================================
# LoongArch 32-bit 测试程序 — 全 ALU 指令覆盖
# 双发射布局: 左列为 slot0 (低32位), 右列为 slot1 (高32位)
# ============================================================

# ── 初始化: $1=7, $2=2 ──
    addi.w  $1, $0, 7       
    addi.w  $2, $0, 2       # PC=0x00

# ── 等待写回 (3对NOP, 保证 $1/$2 在 WB 写入后才被 ID 读到) ──
    addi.w  $0, $0, 0       
    addi.w  $0, $0, 0       # PC=0x08
    addi.w  $0, $0, 0       
    addi.w  $0, $0, 0       # PC=0x10
    addi.w  $0, $0, 0       
    addi.w  $0, $0, 0       # PC=0x18

# ============================================================
# 3R型 ALU (18条, $1=7, $2=2)
# ============================================================
    add.w   $3,  $1, $2      
    sub.w   $4,  $1, $2     # PC=0x20  $3=9,  $4=5
    slt     $5,  $1, $2      
    sltu    $6,  $1, $2     # PC=0x28  $5=0,  $6=0
    nor     $7,  $1, $2      
    and     $8,  $1, $2     # PC=0x30  $7=-8, $8=2
    or      $9,  $1, $2      
    xor     $10, $1, $2     # PC=0x38  $9=7,  $10=5
    sll.w   $11, $1, $2      
    srl.w   $12, $1, $2     # PC=0x40  $11=28, $12=1
    sra.w   $13, $1, $2      
    mul.w   $14, $1, $2     # PC=0x48  $13=1, $14=14
    mulh.w  $15, $1, $2      
    mulh.wu $16, $1, $2     # PC=0x50  $15=0, $16=0
    div.w   $17, $1, $2      
    mod.w   $18, $1, $2     # PC=0x58  $17=3, $18=1
    div.wu  $19, $1, $2      
    mod.wu  $20, $1, $2     # PC=0x60  $19=3, $20=1

# ============================================================
# I型 ALU (6条, $1=7, imm=2)
# ============================================================
    addi.w  $21, $1, 2       
    andi    $22, $1, 2      # PC=0x68  $21=9, $22=2
    ori     $23, $1, 2       
    xori    $24, $1, 2      # PC=0x70  $23=7, $24=5
    slti    $25, $1, 2       
    sltui   $26, $1, 2      # PC=0x78  $25=0, $26=0

# ============================================================
# 移位立即数 (3条) + 特殊 (1条)
# ============================================================
    slli.w  $27, $1, 2       
    srli.w  $28, $1, 2      # PC=0x80  $27=28, $28=1
    srai.w  $29, $1, 2       
    lu12i.w $30, 0           # PC=0x88  $29=1, $30=0

# ============================================================
# 死循环结束
# ============================================================
loop:
    b       loop           