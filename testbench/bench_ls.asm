# ============================================================
# Load/Store 测试
# dmem 初始化为全零, 基址 $r1=0
# ============================================================

# ── 初始化测试数据 ──
    addi.w    $r1, $r0, 0
    addi.w    $r2, $r0, 0x5A
    lu12i.w   $r3, 0x8
    lu12i.w   $r4, 0x12345
    addi.w    $r0, $r0, 0
    addi.w    $r0, $r0, 0
    addi.w    $r0, $r0, 0
    addi.w    $r0, $r0, 0
    addi.w    $r0, $r0, 0
    addi.w    $r0, $r0, 0
    ori       $r3, $r3, 0x765
    ori       $r4, $r4, 0x678

# ── 等待写回 ──
    addi.w    $r0, $r0, 0
    addi.w    $r0, $r0, 0
    addi.w    $r0, $r0, 0
    addi.w    $r0, $r0, 0
    addi.w    $r0, $r0, 0
    addi.w    $r0, $r0, 0

# ============================================================
# Store: 写入地址 0,2,4
# ============================================================
    st.b      $r2, $r1, 0
    addi.w    $r0, $r0, 0
    st.h      $r3, $r1, 2
    addi.w    $r0, $r0, 0
    st.w      $r4, $r1, 4
    addi.w    $r0, $r0, 0

# ── 等待 dmem 写入完成 ──
    addi.w    $r0, $r0, 0
    addi.w    $r0, $r0, 0

# ============================================================
# Load: 读回并验证
# ============================================================

# LD.B  [0]: 0x5A → sign-extend → 0x0000005A
    ld.b      $r5, $r1, 0
    addi.w    $r0, $r0, 0

# LD.BU [0]: 0x5A → zero-extend → 0x0000005A
    ld.bu     $r6, $r1, 0
    addi.w    $r0, $r0, 0

# LD.H  [2]: 0x8765 → sign-extend → 0xFFFF8765
    ld.h      $r7, $r1, 2
    addi.w    $r0, $r0, 0

# LD.HU [2]: 0x8765 → zero-extend → 0x00008765
    ld.hu     $r8, $r1, 2
    addi.w    $r0, $r0, 0

# LD.W  [4]: 0x12345678
    ld.w      $r9, $r1, 4
    addi.w    $r0, $r0, 0

done:
    b         done
    addi.w    $r0, $r0, 0