# ============================================================
# CSR 指令测试
# 复位后 CRMD=0x08 (DA=1), 其余 CSR=0
# plv0 暂时固定为 1
#
# 寄存器初始值:
#   $r12 = 0x00000055  (写入 CRMD 的值)
#   $r13 = 0xAAAAAAAA  (写入 ERA 的值)
#   $r14 = 0x0000000A  (mask: bit3/bit1 写使能)
#   $r15 = 0x00000008  (新值: 仅置 bit3)
#
# 期望结果:
#   $r20 = 0x00000008  (csrrd 读初始 CRMD)
#   $r21 = 0x00000055  (csrrd 读 CSRWR 后的 CRMD)
#   $r22 = 0xAAAAAAAA  (csrrd 读 ERA)
#   $r15 = 0x00000055  (csrxchg 返回旧 CRMD)
#   $r23 = 0x0000005D  (csrrd 读 XCHG 后 CRMD: 0x55|0x8=0x5D)
#   $r12 = 0x00000008  (csrwr 返回旧 CRMD)
#   $r13 = 0x00000000  (csrwr 返回旧 ERA)
# ============================================================

# ── 初始化 ──
    addi.w  $r12, $r0, 0x55
    lu12i.w $r13, -0x55556
    ori     $r13, $r13, 0xAAA       # $r13 = 0xAAAAAAAA
    addi.w  $r14, $r0, 0xA
    addi.w  $r15, $r0, 0x8

# ============================================================
# 1. CSRRD: 读初始 CRMD (期望 0x08)
# ============================================================
    csrrd   $r20, 0x0              # $r20 = 0x00000008

# ============================================================
# 2. CSRWR: 写 CRMD, $r12 ← 旧值 (期望 0x08)
# ============================================================
    csrwr   $r12, 0x0              # CRMD ← 0x55, $r12 ← 0x08

# ============================================================
# 3. CSRRD: 读 CRMD (期望 0x55)
# ============================================================
    csrrd   $r21, 0x0              # $r21 = 0x00000055

# ============================================================
# 4. CSRWR: 写 ERA, $r13 ← 旧值 (期望 0x00)
# ============================================================
    csrwr   $r13, 0x6              # ERA ← 0xAAAAAAAA, $r13 ← 0x00

# ============================================================
# 5. CSRRD: 读 ERA (期望 0xAAAAAAAA)
# ============================================================
    csrrd   $r22, 0x6              # $r22 = 0xAAAAAAAA

# ============================================================
# 6. CSRXCHG: 掩码写 CRMD
#    mask=$r14=0xA (bit3,bit1), val=$r15=0x8 (bit3)
#    旧CRMD=0x55 → 新CRMD=(0x55&~0xA)|(0x8&0xA)=0x55|0x8=0x5D
#    $r15 ← 旧CRMD = 0x55
# ============================================================
    csrxchg $r15, $r14, 0x0       # $r15 ← 0x55, CRMD ← 0x5D

# ============================================================
# 7. CSRRD: 读 CRMD 验证 XCHG (期望 0x5D)
# ============================================================
    csrrd   $r23, 0x0              # $r23 = 0x0000005D

# ── 死循环 ──
end:
    b       end
