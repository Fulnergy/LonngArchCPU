# ============================================================
# ALU 依赖链测试 — 前递全覆盖
# ============================================================

# ── 初始化: $r1=3, $r2=2, $r3=5 ──
    addi.w  $r1, $r0, 3
    addi.w  $r2, $r0, 2
    addi.w  $r3, $r0, 5
    addi.w  $r0, $r0, 0

# ── 等待写回 ──
    addi.w  $r0, $r0, 0
    addi.w  $r0, $r0, 0
    addi.w  $r0, $r0, 0
    addi.w  $r0, $r0, 0
    addi.w  $r0, $r0, 0
    addi.w  $r0, $r0, 0

# ============================================================
# 同槽前递链: $r1 连续自增 (br → br)
# ============================================================
    addi.w  $r1, $r1, 1
    addi.w  $r0, $r0, 0
    addi.w  $r1, $r1, 1
    addi.w  $r0, $r0, 1
    addi.w  $r1, $r1, 1
    addi.w  $r0, $r0, 2
    addi.w  $r1, $r1, 1
    addi.w  $r0, $r0, 3

# $r1=0x7

# ============================================================
# 同拍跨槽前递: 低位算 → 高位用 (br → ls, 同对)
# ============================================================
    addi.w  $r4, $r1, 3
    add.w   $r5, $r4, $r2

# $r4=0xA, $r5=0xC ($r5 依赖 $r4, 同拍跨槽)

# ============================================================
# 同拍跨槽前递: 高位算 → 低位用 (ls → br)
# ============================================================
    add.w   $r6, $r5, $r2
    addi.w  $r7, $r6, 8

# $r6=0xE, $r7=0x16

# ============================================================
# 逻辑链: 连续跨槽依赖
# ============================================================
    and     $r8, $r1, $r2
    xor     $r9, $r8, $r1

    or      $r10, $r9, $r2
    nor     $r11, $r10, $r0

# $r1=0x7, $r2=0x2: $r8=0x2, $r9=0x5, $r10=0x7, $r11=0xFFFFFFF8

# ============================================================
# 移位链: 同槽 + 跨槽
# ============================================================
    slli.w  $r12, $r1, 1
    srli.w  $r13, $r12, 2

    sll.w   $r14, $r13, $r2
    sra.w   $r15, $r14, $r3

# $r12=0xE, $r13=0x3, $r14=0xC, $r15=0x0

# ============================================================
# I型 + 比较链
# ============================================================
    slti    $r16, $r1, 10
    sltui   $r17, $r1, 10

    andi    $r18, $r16, 1
    ori     $r19, $r17, 0x100

# $r16=0x1, $r17=0x1, $r18=0x1, $r19=0x101

# ============================================================
# 乘除链: 同拍依赖
# ============================================================
    mul.w   $r20, $r1, $r2
    mulh.w  $r21, $r20, $r1

    div.w   $r22, $r20, $r2
    mod.w   $r23, $r20, $r2

# $r20=0xE, $r21=0x0, $r22=0x7, $r23=0x0

# ============================================================
# 特殊指令链
# ============================================================
    lu12i.w $r24, 0x1
    addi.w  $r24, $r24, 0x234

    pcaddu12i $r25, 0
    addi.w    $r25, $r25, 0

# $r24=0x1234, $r25=PC

# ============================================================
# 死循环
# ============================================================
done:
    b       done
    addi.w  $r0, $r0, 0
