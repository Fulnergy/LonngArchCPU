# ============================================================
# Fibonacci 测试
# 从 dmem[0] 取 x, 计算 fib(x)
#
# 寄存器分配:
#   $r0  = 0 (硬连线)
#   $r12 = x (从 dmem[0] load)
#   $r13 = a  = fib(i-2)          迭代用
#   $r14 = b  = fib(i-1)          迭代用; 循环结束后 = fib(x)
#   $r15 = i  (循环计数, 初值 2)
#   $r16 = c  = a + b (临时)
#   $r20 = fib(x) (最终结果)
#
# 算法: 迭代 fib, i 从2递增, 每次 c=a+b, a←b, b←c
#       当 x < i 时退出, 此时 b = fib(x)
#       特判 x=0 → fib(0)=0
# ============================================================

# ── 取 x: $r12 = dmem[0] ──
    ld.w    $r12, $r0, 0          # $r12 = x


# ============================================================
# 初始化迭代变量
# ============================================================
    addi.w  $r13, $r0, 0          # $r13 = a = 0
    addi.w  $r14, $r0, 1          # $r14 = b = 1
    addi.w  $r15, $r0, 2          # $r15 = i = 2
    beq     $r12, $r0, fib_zero   # if x==0, jump fib_zero

# ============================================================
# 主循环: while (i <= x)
# ============================================================
fib_loop:
    blt     $r12, $r15, fib_done  # if x < i, exit loop
    add.w   $r16, $r13, $r14      # $r16 = c = a + b
    or      $r13, $r14, $r0       # $r13 = a ← b
    or      $r14, $r16, $r0       # $r14 = b ← c
    addi.w  $r15, $r15, 1         # $r15 = i++
    b       fib_loop              # 继续循环

# ============================================================
# x == 0 特判: fib(0) = 0
# ============================================================
fib_zero:
    addi.w  $r14, $r0, 0          # $r14 = b = 0

# ============================================================
# 结束: $r20 = fib(x)
# ============================================================
fib_done:
    or      $r20, $r14, $r0       # $r20 = fib(x) = b

# ── 死循环 ──
end:
    b       end
